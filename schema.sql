ALTER TABLE public.evidents ADD COLUMN IF NOT EXISTS photo_type TEXT;

-- Buat Index untuk mempercepat validasi ODC/ODP, pelanggan, dan pencegahan duplikat
CREATE INDEX IF NOT EXISTS idx_evidents_category ON public.evidents(category);
CREATE INDEX IF NOT EXISTS idx_evidents_device_label ON public.evidents(device_label);
CREATE INDEX IF NOT EXISTS idx_evidents_customer_id ON public.evidents(customer_id);
CREATE INDEX IF NOT EXISTS idx_evidents_modem_sn ON public.evidents(modem_sn);
