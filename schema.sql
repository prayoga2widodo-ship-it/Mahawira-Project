-- 9. SISTEM LOGISTIK & PENGELOLAAN MATERIAL (GUDANG, RETURN & REFURBISH)
-- ==============================================================================

-- 9.1 Tabel Master Stok Barang (Inventory)
CREATE TABLE IF NOT EXISTS public.materials_inventory (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,                          -- Nama barang (contoh: 'Kabel Dropcore 1 Core 3 Seling', 'Modem ONT ZTE F609', 'Pigtail SC/UPC')
    category TEXT NOT NULL DEFAULT 'Aksesoris',         -- Kategori (Kabel, Modem/ONT, Pasif/ODP, Aksesoris, Alat Kerja)
    unit TEXT NOT NULL DEFAULT 'pcs',                   -- Satuan (pcs, roll, meter, unit, pack)
    stock_new INT NOT NULL DEFAULT 0,                   -- Stok Barang Baru Siap Pakai
    stock_refurbish INT NOT NULL DEFAULT 0,             -- Stok Barang Refurbish / Bekas Tarikan yang Layak
    stock_damaged INT NOT NULL DEFAULT 0,               -- Stok Barang Rusak / Afkir
    min_stock_alert INT DEFAULT 5,                      -- Batas Peringatan Stok Menipis
    notes TEXT,                                         -- Keterangan / Deskripsi
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 9.2 Tabel Mutasi & Transaksi Material (Ambil, Return Sisa, Refurbish)
CREATE TABLE IF NOT EXISTS public.material_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_type TEXT NOT NULL,                     -- 'OUT' (Pengambilan), 'RETURN_UNUSED' (Return Sisa), 'REFURBISH' (Pengembalian Tarikan)
    material_name TEXT NOT NULL,                        -- Nama barang
    quantity INT NOT NULL DEFAULT 1,                    -- Jumlah barang
    unit TEXT DEFAULT 'pcs',                            -- Satuan (meter, pcs, unit)
    
    -- Khusus Perangkat (Modem / ONT / OLT / Aksesoris Bernomor Seri)
    serial_number TEXT,                                 -- Nomor seri / MAC Address jika ada
    item_condition TEXT DEFAULT 'Bagus',                -- 'Bagus / Baru', 'Layak Pakai (Refurbish)', 'Rusak Ringan', 'Mati Total'
    
    -- Identitas Keperluan & Target Lapangan
    project_target TEXT,                                -- Contoh: 'PSB Pelanggan ID-10029', 'Maintenance ODC-SKD 01', 'Pemasangan ODP-KT 055/001'
    notes TEXT,                                         -- Catatan teknisi
    
    -- Evident Foto Fisik Serah Terima / Pengembalian
    file_url TEXT,                                      -- URL Foto di Supabase Storage
    
    -- Identitas Teknisi & Pelacak GPS
    uploader TEXT NOT NULL,                             -- Nama Teknisi / ID Telegram
    telegram_chat_id TEXT,                              -- Chat ID Telegram teknisi
    date TEXT NOT NULL,                                 -- Waktu rekam lokal (contoh: '26/11/2026, 10:30')
    latitude DOUBLE PRECISION,                          -- Lokasi GPS saat serah terima
    longitude DOUBLE PRECISION,
    location_url TEXT,
    
    -- Verifikasi Admin Gudang
    status TEXT DEFAULT 'Pending',                      -- 'Pending', 'Verified / Diterima', 'Rejected'
    verified_by TEXT,                                   -- Admin gudang yang memverifikasi fisik
    verified_at TIMESTAMPTZ,
    
    created_at TIMESTAMPTZ DEFAULT NOW()
);

