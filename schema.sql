-- ==============================================================================
-- 6. VIEW DATABASE (Opsional: Memudahkan Tampilan Supabase Table Editor seperti Dashboard)
-- ==============================================================================

-- View 1: Tampilan Tabel Standar Dashboard
CREATE OR REPLACE VIEW public.v_evident_dashboard AS
SELECT 
    id,
    name AS "File Evident",
    customer_id AS "ID Pelanggan",
    customer_name AS "Nama Pelanggan",
    modem_sn AS "SN Modem",
    COALESCE(odp_reference, device_label) AS "Nama ODP",
    category AS "Kategori",
    odc_reference AS "Induk ODC",
    photo_type AS "Jenis Foto",
    latitude AS "Latitude GPS",
    longitude AS "Longitude GPS",
    location_url AS "Link Google Maps",
    uploader AS "Pengunggah",
    date AS "Tanggal & Waktu",
    status AS "Status",
    size AS "Ukuran",
    file_url AS "URL Foto"
FROM public.evidents
ORDER BY id DESC;

-- View 2: Tampilan Khusus Pelanggan & Modem
CREATE OR REPLACE VIEW public.v_evident_modem AS
SELECT 
    id,
    customer_id AS "ID Pelanggan",
    customer_name AS "Nama Pelanggan",
    modem_sn AS "SN Modem",
    COALESCE(odp_reference, device_label) AS "ODP Terhubung",
    odc_reference AS "Induk ODC",
    photo_type AS "Tampak Foto",
    latitude AS "Lat",
    longitude AS "Lng",
    location_url AS "Peta Lokasi",
    uploader AS "Teknisi",
    date AS "Tanggal Pasang",
    file_url AS "Foto Evident"
FROM public.evidents
WHERE category = 'MODEM' OR customer_id IS NOT NULL OR modem_sn IS NOT NULL
ORDER BY id DESC;

-- View 3: Tampilan Khusus Aset GIS & Peta KML (Memiliki Koordinat GPS)
CREATE OR REPLACE VIEW public.v_evident_gis_kml AS
SELECT 
    id,
    category AS "Kategori Aset",
    COALESCE(device_label, name) AS "Nama Aset",
    latitude AS "Latitude",
    longitude AS "Longitude",
    location_url AS "Google Maps",
    odc_reference AS "Induk ODC",
    customer_name AS "Pelanggan",
    file_url AS "Foto"
FROM public.evidents
WHERE latitude IS NOT NULL AND longitude IS NOT NULL
ORDER BY id DESC;

