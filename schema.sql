-- 1. TABEL UTAMA: public.evidents (Menyimpan seluruh data dan foto berkas evident)
-- Kolom disesuaikan dengan urutan dan kebutuhan Tabel Web Dashboard:
-- [File Evident, ID Pelanggan, Nama Pelanggan, SN Modem, Nama ODP, Kategori,
--  Share Loc / Koordinat, Pengunggah, Tanggal & Waktu, Status, dan Foto]
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.evidents (
    -- Primary Key & Identitas Baris
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Kolom 1: Berkas & Identitas Perangkat
    name TEXT NOT NULL,                                 -- Nama berkas / evident foto
    file_url TEXT,                                      -- URL publik berkas foto di Supabase Storage
    size TEXT DEFAULT '0 MB',                           -- Ukuran berkas (contoh: '1.5 MB')
    category TEXT NOT NULL,                             -- Kategori / Folder (contoh: 'ODC', 'ODP', 'TIANG', 'MODEM')
    device_label TEXT,                                  -- Label fisik perangkat (contoh: 'ODP-SKD 01/01', 'ODC-SKD 01', 'TIANG-01')
    photo_type TEXT,                                    -- Jenis foto: 'TAMPAK LUAR', 'TAMPAK DALAM', 'REDAMAN', 'LABEL', 'DEPAN', 'BELAKANG'

    -- Kolom 2 - 5: Data Pelanggan, Modem & Relasi Jaringan (Tabel Dashboard)
    customer_id TEXT,                                   -- ID Pelanggan (contoh: '10293847')
    customer_name TEXT,                                 -- Nama Pelanggan (contoh: 'Budi Santoso')
    modem_sn TEXT,                                      -- Nomor seri modem (contoh: 'ZTEGC123456')
    odp_reference TEXT,                                 -- Nama ODP tempat modem/pelanggan terhubung (contoh: 'ODP-SKD 01/01')
    odc_reference TEXT,                                 -- Induk ODC dari perangkat ODP/Modem (contoh: 'ODC-SKD 01')

    -- Kolom 6: Share Loc & Titik Koordinat GPS Lapangan
    latitude DOUBLE PRECISION,                          -- Titik Garis Lintang (Latitude GPS)
    longitude DOUBLE PRECISION,                         -- Titik Garis Bujur (Longitude GPS)
    location_url TEXT,                                  -- Link Navigasi Google Maps (contoh: 'https://maps.google.com/?q=-7.123,110.123')

    -- Kolom 7 - 9: Pengunggah, Waktu & Verifikasi
    uploader TEXT,                                      -- Identitas pengunggah (Email Dashboard / Nama Teknisi / ID Telegram)
    date TEXT,                                          -- Waktu & Tanggal upload (contoh: '23/11/2026, 11:30:00')
    status TEXT DEFAULT 'Pending Review',               -- Status: 'Pending Review', 'Verified', 'Rejected'
    reject_reason TEXT,                                 -- Alasan penolakan jika status 'Rejected'

    -- Kolom Keamanan & Validasi Anti-Fraud (Deteksi Foto Kembar / Duplikat)
    image_hash TEXT,                                    -- Hash SHA-256 berkas foto identik
    perceptual_hash TEXT,                               -- Perceptual dHash 64-bit anti screenshot / kompresi ulang
    
    -- Timestamp Database
    created_at TIMESTAMPTZ DEFAULT NOW()                -- Waktu pencatatan data ke database
);

