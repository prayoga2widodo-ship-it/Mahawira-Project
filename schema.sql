-- 1. TABEL: evidents (Menyimpan data dan foto evident: ODC, TIANG, ODP, MODEM)
CREATE TABLE IF NOT EXISTS public.evidents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    size TEXT,
    category TEXT NOT NULL,
    device_label TEXT,
    odc_reference TEXT,
    customer_id TEXT,
    customer_name TEXT,
    modem_sn TEXT,
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    location_url TEXT,
    uploader TEXT,
    date TEXT,
    status TEXT DEFAULT 'Pending Review',
    file_url TEXT,
    reject_reason TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

